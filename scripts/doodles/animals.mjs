// --- Local helpers -----------------------------------------------------------

const rad = (deg) => (deg * Math.PI) / 180

/** A point on an ellipse; angles in degrees, 0 is right, 90 is down. */
const at = (cx, cy, rx, ry, deg) => [cx + Math.cos(rad(deg)) * rx, cy + Math.sin(rad(deg)) * ry]

/** The y of an ellipse's top (-1) or bottom (+1) edge at x, for hanging legs off a body. */
const edgeY = (cx, cy, rx, ry, x, side = 1) => cy + side * ry * Math.sqrt(Math.max(0, 1 - ((x - cx) / rx) ** 2))

/** A bumpy, cloud-like outline (wool, manes) along part of an ellipse. */
function cloud(cx, cy, rx, ry, bumps, from = 0, to = 360, puff = 0.35) {
  const pts = []
  for (let i = 0; i < bumps; i++) {
    const a0 = from + ((to - from) * i) / bumps
    const a1 = from + ((to - from) * (i + 1)) / bumps
    const p0 = at(cx, cy, rx, ry, a0)
    const p1 = at(cx, cy, rx, ry, a1)
    const m = at(cx, cy, rx, ry, (a0 + a1) / 2)
    const len = Math.hypot(m[0] - cx, m[1] - cy) || 1
    const h = Math.hypot(p1[0] - p0[0], p1[1] - p0[1]) * puff
    for (let k = i === 0 ? 0 : 1; k <= 4; k++) {
      const t = k / 4
      const s = Math.sin(Math.PI * t) * h
      pts.push([p0[0] + (p1[0] - p0[0]) * t + ((m[0] - cx) / len) * s, p0[1] + (p1[1] - p0[1]) * t + ((m[1] - cy) / len) * s])
    }
  }
  return curve(...pts)
}

/** Points along a Catmull-Rom path, densely sampled. */
function path(points, per = 12) {
  const P = [points[0], ...points, points.at(-1)]
  const out = []
  for (let i = 1; i < P.length - 2; i++) {
    const [p0, p1, p2, p3] = [P[i - 1], P[i], P[i + 1], P[i + 2]]
    for (let k = 0; k < per; k++) {
      const t = k / per
      const f = (a, b, c, d) =>
        0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t * t + (-a + 3 * b - 3 * c + d) * t * t * t)
      out.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])])
    }
  }
  out.push(points.at(-1))
  return out
}

/** The two edges of a tube along a path, from half-width w0 to w1; plus the dense centre line. */
function tubeEdges(points, w0, w1) {
  const c = path(points)
  const left = []
  const right = []
  c.forEach(([x, y], i) => {
    const [ax, ay] = c[Math.max(0, i - 1)]
    const [bx, by] = c[Math.min(c.length - 1, i + 1)]
    const len = Math.hypot(bx - ax, by - ay) || 1
    const nx = -(by - ay) / len
    const ny = (bx - ax) / len
    const w = w0 + ((w1 - w0) * i) / (c.length - 1)
    left.push([x + nx * w, y + ny * w])
    right.push([x - nx * w, y - ny * w])
  })
  return { left, right, centre: c }
}

/** Thins a dense point list so curve() can smooth it with a hand's wobble. */
const thin = (pts, every = 4) => pts.filter((_, i) => i % every === 0 || i === pts.length - 1)

/** A blotchy spot (giraffe, cow). */
const spot = (x, y, r) => blob([x - r, y], [x - r * 0.3, y - r * 0.9], [x + r * 0.8, y - r * 0.6], [x + r, y + r * 0.3], [x + r * 0.2, y + r * 0.9], [x - r * 0.7, y + r * 0.7])

/** A slim leg drawn as a U, with a hoof line near the bottom. */
const hoofLeg = (x, top, bottom, w = 34) => [line([x, top], [x, bottom], [x + w, bottom], [x + w, top]), line([x, bottom - 28], [x + w, bottom - 28])]

/** Three little toes fanning from a point. */
const toes = (x, y, dir = -1, len = 40) => [line([x, y], [x + dir * len, y + 12]), line([x, y], [x + dir * len * 0.4, y + 30]), line([x, y], [x - dir * len * 0.5, y + 18])]

/** Two antennae with knobs, from (x, y) splaying up. */
const antennae = (x0, y0, x1, y1, spread = 120, height = 150, knob = 14) => [
  curve([x0, y0], [x0 - spread * 0.4, y0 - height * 0.7], [x0 - spread, y0 - height]),
  circle(x0 - spread, y0 - height, knob),
  curve([x1, y1], [x1 + spread * 0.4, y1 - height * 0.7], [x1 + spread, y1 - height]),
  circle(x1 + spread, y1 - height, knob),
]

