/** Points pushed sideways off a path by `d` (a number, or a function of 0..1 along it). */
function offset(pts, d) {
  return pts.map((p, i) => {
    const a = pts[Math.max(0, i - 1)]
    const b = pts[Math.min(pts.length - 1, i + 1)]
    const dx = b[0] - a[0]
    const dy = b[1] - a[1]
    const len = Math.hypot(dx, dy) || 1
    const k = typeof d === 'function' ? d(i / (pts.length - 1)) : d
    return [p[0] - (dy / len) * k, p[1] + (dx / len) * k]
  })
}

/** The two edges of a tube along a path; `w` is its width (number or function of 0..1). */
function tube(pts, w) {
  const half = typeof w === 'function' ? (t) => w(t) / 2 : () => w / 2
  return [curve(...offset(pts, half)), curve(...offset(pts, (t) => -half(t)))]
}

const sparkle = (x, y, r) => star(x, y, r, r * 0.3, 4)

/** A run of bumps between consecutive points (feather tips, icing, wing webs). */
function scallops(pts, bulge) {
  const out = []
  for (let i = 0; i + 1 < pts.length; i++) {
    const [ax, ay] = pts[i]
    const [bx, by] = pts[i + 1]
    const len = Math.hypot(bx - ax, by - ay) || 1
    const mx = (ax + bx) / 2 - ((by - ay) / len) * bulge * 2
    const my = (ay + by) / 2 + ((bx - ax) / len) * bulge * 2
    for (let k = i ? 1 : 0; k <= 8; k++) {
      const t = k / 8
      out.push([(1 - t) ** 2 * ax + 2 * t * (1 - t) * mx + t * t * bx, (1 - t) ** 2 * ay + 2 * t * (1 - t) * my + t * t * by])
    }
  }
  return curve(...out)
}

/** A teardrop flame on (cx, by): round bottom, tip `lean` to the side at height `h`. */
function flame(cx, by, w, h, lean = 0) {
  const tip = [cx + lean, by - h]
  return [
    arc(cx, by - h * 0.3, w / 2, h * 0.3, 0, 180),
    curve([cx - w / 2, by - h * 0.3], [cx - w * 0.38 + lean * 0.2, by - h * 0.6], [cx - w * 0.1 + lean * 0.6, by - h * 0.85], tip),
    curve([cx + w / 2, by - h * 0.3], [cx + w * 0.35 + lean * 0.2, by - h * 0.55], [cx + w * 0.12 + lean * 0.5, by - h * 0.78], tip),
  ]
}

/** A campfire-style blaze on (cx, by): a round base and five wavy tongues, with a flame inside. */
function blaze(cx, by, w, h) {
  const P = (x, y) => [cx + x * w, by - y * h]
  const tips = [[-0.42, 0.7], [-0.16, 0.9], [0.06, 1], [0.26, 0.82], [0.46, 0.64]]
  const valleys = [[-0.24, 0.4], [-0.04, 0.52], [0.16, 0.48], [0.33, 0.36]]
  const out = [
    arc(cx, by - h * 0.15, w * 0.42, h * 0.15, 0, 180),
    curve(P(-0.42, 0.15), P(-0.5, 0.35), P(-0.4, 0.5), P(...tips[0])),
    curve(P(...tips[4]), P(0.5, 0.4), P(0.42, 0.15)),
    flame(cx, by - h * 0.03, w * 0.3, h * 0.55, w * 0.04),
  ]
  valleys.forEach((v, i) => {
    const t = tips[i]
    const n = tips[i + 1]
    out.push(curve(P(...t), P(t[0] + 0.07, (t[1] + v[1]) / 2 + 0.02), P(...v)))
    out.push(curve(P(...v), P((v[0] + n[0]) / 2 - 0.05, (v[1] + n[1]) / 2), P(...n)))
  })
  return out
}

/** A puffy cloud. */
function cloud(cx, cy, rx, ry, bumps = 7) {
  const pts = []
  for (let i = 0; i < 72; i++) {
    const a = (i / 72) * Math.PI * 2
    const k = 1 + 0.16 * Math.abs(Math.sin((a * bumps) / 2))
    pts.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k])
  }
  return blob(...pts)
}

/** A leaf from a stem point, pointing `dir` (+1 right, -1 left). */
function leaf(x, y, dir, size) {
  const tip = [x + dir * size, y - size * 0.35]
  return [
    blob([x, y], [x + dir * size * 0.45, y - size * 0.45], tip, [x + dir * size * 0.55, y + size * 0.1]),
    line([x, y], [x + dir * size * 0.75, y - size * 0.25]),
  ]
}

