// Local helpers.
/** Joins several strokes into one continuous stroke, like a pen that never lifts. */
const path = (...parts) => ({ e: false, p: parts.flatMap((s) => s.p) })
/** Mirrors a list of points across x = cx. */
const mx = (pts, cx = 500) => pts.map(([x, y]) => [2 * cx - x, y])
/** A symmetric closed outline from its left half (top centre round to bottom centre). */
const sym = (half, cx = 500) => curve(...half, ...mx(half, cx).reverse().slice(1))
/** A teardrop, point up, round bottom centred on (x, y). */
const drop = (x, y, s) =>
  curve(
    [x, y - 1.8 * s],
    [x + 0.55 * s, y - 0.8 * s],
    [x + s, y],
    [x + 0.7 * s, y + 0.7 * s],
    [x, y + s],
    [x - 0.7 * s, y + 0.7 * s],
    [x - s, y],
    [x - 0.55 * s, y - 0.8 * s],
    [x, y - 1.8 * s],
  )
/** Points along an ellipse whose radius bulges in `n` bumps, for brains, beards and clouds. */
const bumps = (cx, cy, rx, ry, from, to, n, amp) => {
  const pts = []
  const steps = n * 6
  for (let i = 0; i <= steps; i++) {
    const t = i / steps
    const a = ((from + (to - from) * t) * Math.PI) / 180
    const k = 1 + amp * Math.abs(Math.sin(t * n * Math.PI))
    pts.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k])
  }
  return pts
}
