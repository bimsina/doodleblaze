// --- Local helpers ---

const rad = (deg) => (deg * Math.PI) / 180
/** A point on a circle or ellipse, angle in degrees (0 right, 90 down). */
const at = (cx, cy, rx, deg, ry = rx) => [
  cx + Math.cos(rad(deg)) * rx,
  cy + Math.sin(rad(deg)) * ry,
]
/** The points of an arc, for splicing into a longer line. */
const arcPts = (cx, cy, rx, ry, from, to, n = 10) =>
  Array.from({ length: n + 1 }, (_, i) =>
    at(cx, cy, rx, from + ((to - from) * i) / n, ry),
  )
/** A careful, ruler-straight line through these points (for small repeated parts like comb teeth). */
const steady = (...points) => ({
  e: false,
  p: points.flatMap(([x, y], i) => [
    Math.round(x + ((i * 7) % 5) - 2),
    Math.round(y + ((i * 3) % 5) - 2),
  ]),
})
/** A rectangle with rounded corners. */
function roundRect(x, y, w, h, r) {
  return line(
    ...arcPts(x + w - r, y + r, r, r, -90, 0, 4),
    ...arcPts(x + w - r, y + h - r, r, r, 0, 90, 4),
    ...arcPts(x + r, y + h - r, r, r, 90, 180, 4),
    ...arcPts(x + r, y + r, r, r, 180, 270, 4),
    [x + w - r, y],
  )
}

