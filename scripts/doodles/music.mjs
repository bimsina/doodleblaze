/** Points pushed sideways off a path by `d` (a number, or a function of 0..1 along it). */
function offset(pts, d) {
  return pts.map((p, i) => {
    const a = pts[Math.max(0, i - 1)]
    const b = pts[Math.min(pts.length - 1, i + 1)]
    const dx = b[0] - a[0]
    const dy = b[1] - a[1]
    const len = Math.hypot(dx, dy) || 1
    const k = typeof d === 'function' ? d(i / (pts.length - 1)) : d
    return [p[0] - (dy / len) * k, p[1] + (dx / len) * k]
  })
}

/** The two edges of a tube along a path; `w` is its width (number or function of 0..1). */
function tube(pts, w) {
  const half = typeof w === 'function' ? (t) => w(t) / 2 : () => w / 2
  return [curve(...offset(pts, half)), curve(...offset(pts, (t) => -half(t)))]
}

const sparkle = (x, y, r) => star(x, y, r, r * 0.3, 4)

/** A curly cord: loops of radius `r` along a straight run. */
function coil(x0, y0, x1, y1, n = 8, r = 25) {
  const pts = []
  for (let i = 0; i <= n * 12; i++) {
    const t = i / (n * 12)
    const a = t * n * Math.PI * 2
    pts.push([x0 + (x1 - x0) * t + Math.cos(a) * r, y0 + (y1 - y0) * t + Math.sin(a) * r])
  }
  return curve(...pts)
}

/** A shape mirrored about x = 500: give the right half, top to bottom. */
function symmetric(right) {
  const left = right.slice(1, -1).reverse().map(([x, y]) => [1000 - x, y])
  return blob(...right, ...left)
}

