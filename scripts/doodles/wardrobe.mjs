// --- Local helpers -----------------------------------------------------------

const rad = (deg) => (deg * Math.PI) / 180
const polar = (cx, cy, r, deg) => [cx + Math.cos(rad(deg)) * r, cy + Math.sin(rad(deg)) * r]

/** A rounded rectangle as one closed stroke. */
function rrect(x, y, w, h, r = Math.min(w, h) * 0.2) {
  const pts = []
  const corner = (cx, cy, from) => {
    for (let i = 0; i <= 4; i++) pts.push(polar(cx, cy, r, from + i * 22.5))
  }
  corner(x + w - r, y + r, -90)
  corner(x + w - r, y + h - r, 0)
  corner(x + r, y + h - r, 90)
  corner(x + r, y + r, 180)
  return line(...pts, pts[0])
}

/** A fluffy, scalloped ring, like a pom-pom or an ear muff. */
function fluffy(cx, cy, r, bumps = 10, depth = 0.12) {
  const pts = []
  const n = bumps * 6
  for (let i = 0; i <= n; i++) {
    const a = (i / n) * Math.PI * 2
    const k = 1 + depth * Math.abs(Math.sin((a * bumps) / 2))
    pts.push([cx + Math.cos(a) * r * k, cy + Math.sin(a) * r * k])
  }
  return curve(...pts)
}

/** Short parallel lines across a band, like knitted ribbing. */
const ribs = (x0, x1, y0, y1, n) => Array.from({ length: n }, (_, i) => line([x0 + ((x1 - x0) * (i + 1)) / (n + 1), y0], [x0 + ((x1 - x0) * (i + 1)) / (n + 1), y1]))

/** A tiny sparkle. */
const sparkle = (x, y, s = 30) => [line([x - s, y], [x + s, y]), line([x, y - s], [x, y + s])]

