const sparkle = (x, y, r = 30) => star(x, y, r, r * 0.3, 4, -90)

/** A straight bar of width `w` from a to b, as one closed outline. */
function bar([x0, y0], [x1, y1], w) {
  const len = Math.hypot(x1 - x0, y1 - y0) || 1
  const nx = (-(y1 - y0) / len) * (w / 2)
  const ny = ((x1 - x0) / len) * (w / 2)
  return shape([x0 + nx, y0 + ny], [x1 + nx, y1 + ny], [x1 - nx, y1 - ny], [x0 - nx, y0 - ny])
}

/** A tapering limb (arm, leg) along a path: width w0 at the start, w1 at the end. One closed outline. */
function limb(points, w0, w1) {
  const n = points.length
  const left = []
  const right = []
  for (let i = 0; i < n; i++) {
    const [x, y] = points[i]
    const [ax, ay] = points[Math.max(0, i - 1)]
    const [bx, by] = points[Math.min(n - 1, i + 1)]
    const len = Math.hypot(bx - ax, by - ay) || 1
    const w = (w0 + ((w1 - w0) * i) / (n - 1)) / 2
    left.push([x - ((by - ay) / len) * w, y + ((bx - ax) / len) * w])
    right.push([x + ((by - ay) / len) * w, y - ((bx - ax) / len) * w])
  }
  return curve(...left, ...right.reverse(), left[0])
}

/** Points along an ellipse whose radius bulges in `n` bumps, for beards, hair and clouds. */
function bumps(cx, cy, rx, ry, from, to, n, amp) {
  const pts = []
  const steps = n * 6
  for (let i = 0; i <= steps; i++) {
    const t = i / steps
    const a = ((from + (to - from) * t) * Math.PI) / 180
    const k = 1 + amp * Math.abs(Math.sin(t * n * Math.PI))
    pts.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k])
  }
  return pts
}

/** A ring of scallops round an ellipse, bowing outwards: ruffs and frills. */
function frill(cx, cy, rx, ry, n, depth) {
  const p = []
  for (let i = 0; i < n; i++) {
    const a0 = (i / n) * Math.PI * 2
    const a1 = ((i + 1) / n) * Math.PI * 2
    const am = (a0 + a1) / 2
    const seg = curve(
      [cx + Math.cos(a0) * rx, cy + Math.sin(a0) * ry],
      [cx + Math.cos(am) * (rx + depth), cy + Math.sin(am) * (ry + depth)],
      [cx + Math.cos(a1) * rx, cy + Math.sin(a1) * ry],
    )
    p.push(...(i ? seg.p.slice(2) : seg.p))
  }
  return { e: false, p }
}

/** A crescent moon of radius r, its hollow facing right. */
function crescent(cx, cy, r) {
  const outer = []
  for (let a = 45; a <= 315; a += 15) outer.push([cx + Math.cos((a * Math.PI) / 180) * r, cy + Math.sin((a * Math.PI) / 180) * r])
  const ix = cx + r * 0.5
  const ir = r * 0.737
  const inner = []
  for (let a = 286; a >= 74; a -= 16) inner.push([ix + Math.cos((a * Math.PI) / 180) * ir, cy + Math.sin((a * Math.PI) / 180) * ir])
  return curve(...outer, ...inner, outer[0])
}

/** One stroke through these points, each span bowed sideways by `depth`: fluffy, scalloped edges. */
function scallops(points, depth) {
  const p = []
  for (let i = 0; i < points.length - 1; i++) {
    const [ax, ay] = points[i]
    const [bx, by] = points[i + 1]
    const len = Math.hypot(bx - ax, by - ay) || 1
    const mid = [(ax + bx) / 2 + ((by - ay) / len) * depth, (ay + by) / 2 - ((bx - ax) / len) * depth]
    const seg = curve([ax, ay], mid, [bx, by])
    p.push(...(i ? seg.p.slice(2) : seg.p))
  }
  return { e: false, p }
}

/** Diagonal shading clipped to a polygon (lines of the given slope), for dark cloth. */
function hatchPoly(pts, step, slope = 1) {
  const out = []
  const cs = pts.map(([x, y]) => y - slope * x)
  for (let c = Math.min(...cs) + step / 2; c < Math.max(...cs); c += step) {
    const hits = []
    for (let i = 0; i < pts.length; i++) {
      const [x0, y0] = pts[i]
      const [x1, y1] = pts[(i + 1) % pts.length]
      const f0 = y0 - slope * x0 - c
      const f1 = y1 - slope * x1 - c
      if (f0 <= 0 !== f1 <= 0) hits.push(x0 + (x1 - x0) * (f0 / (f0 - f1)))
    }
    hits.sort((a, b) => a - b)
    for (let i = 0; i + 1 < hits.length; i += 2) {
      const a = hits[i] + 5
      const b = hits[i + 1] - 5
      if (b - a > 10) out.push(line([a, slope * a + c], [b, slope * b + c]))
    }
  }
  return out
}

/** Diagonal shading across a disc, leaving the band y0..y1 bare: a dark hood with an eye slit. */
function hatchDisc(cx, cy, r, step, y0 = -1, y1 = -1) {
  const out = []
  const k = Math.SQRT1_2
  for (let d = -r + step / 2; d < r; d += step) {
    const h = Math.sqrt(r * r - d * d)
    const at = (s) => [cx + (d + s) * k, cy + (-d + s) * k]
    const b0 = (y0 - cy) / k + d
    const b1 = (y1 - cy) / k + d
    const pieces = y1 > y0 ? [[-h, Math.min(h, b0)], [Math.max(-h, b1), h]] : [[-h, h]]
    for (const [s0, s1] of pieces) if (s1 - s0 > 14) out.push(line(at(s0 + 4), at(s1 - 4)))
  }
  return out
}

