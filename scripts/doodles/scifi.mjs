/** A small four-point twinkle. */
const sparkle = (x, y, r = 30) => star(x, y, r, r * 0.3, 4, -90)

/** A straight bar of width `w` from a to b, as one closed outline. */
function bar([x0, y0], [x1, y1], w) {
  const len = Math.hypot(x1 - x0, y1 - y0) || 1
  const nx = (-(y1 - y0) / len) * (w / 2)
  const ny = ((x1 - x0) / len) * (w / 2)
  return shape([x0 + nx, y0 + ny], [x1 + nx, y1 + ny], [x1 - nx, y1 - ny], [x0 - nx, y0 - ny])
}

/** Point t of the way from a to b. */
const lerp = ([x0, y0], [x1, y1], t) => [x0 + (x1 - x0) * t, y0 + (y1 - y0) * t]

/** A four-cornered panel (any perspective) with an n x m grid of cells. */
function gridPanel(tl, tr, br, bl, cols, rows) {
  const out = [shape(tl, tr, br, bl)]
  for (let i = 1; i < cols; i++) out.push(line(lerp(tl, tr, i / cols), lerp(bl, br, i / cols)))
  for (let j = 1; j < rows; j++) out.push(line(lerp(tl, bl, j / rows), lerp(tr, br, j / rows)))
  return out
}

/** A flame licking downward from (x, y). */
const flameDown = (x, y, w, h) => [
  curve([x - w, y], [x - w * 0.9, y + h * 0.45], [x - w * 0.3, y + h * 0.7], [x, y + h], [x + w * 0.3, y + h * 0.7], [x + w * 0.9, y + h * 0.45], [x + w, y]),
  curve([x - w * 0.45, y], [x - w * 0.3, y + h * 0.4], [x, y + h * 0.6], [x + w * 0.3, y + h * 0.4], [x + w * 0.45, y]),
]

